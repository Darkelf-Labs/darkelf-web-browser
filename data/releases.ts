import shadowReleaseData from "./shadow-release.generated.json";
import cocoaReleaseData from "./cocoa-release.generated.json";

export type ProductId = "cocoa" | "shadow";

export type Channel =
  | "stable"
  | "beta"
  | "alpha"
  | "lts";

export type Platform =
  | "windows"
  | "linux"
  | "macos";

export type Architecture =
  | "x64"
  | "arm64"
  | "universal"
  | "any";

export type FileType =
  | "pypi"
  | "exe"
  | "appimage"
  | "dmg"
  | "zip"
  | "tar.gz";

export interface Artifact {
  platform: Platform;
  arch: Architecture;
  fileType: FileType;
  url: string;
  sizeBytes?: number;
  sha256?: string;
  notesUrl?: string;
  installCommand?: string;
}

export interface Release {
  product: ProductId;
  channel: Channel;
  version: string;
  dateISO: string;
  releasePageUrl: string;
  zipballUrl: string;
  highlights: string[];
  notesMarkdown?: string;
  artifacts: Artifact[];
}

// Both products are generated by scripts/sync-releases.mjs
// from their latest published, non-prerelease GitHub releases.
const shadowGenerated =
  shadowReleaseData as Release;

const cocoaGenerated =
  cocoaReleaseData as Release;

const shadowRelease: Release = {
  ...shadowGenerated,

  highlights: [
    "Improved privacy and fingerprinting protections",
    "Enhanced tracker and content filtering",
    "Refined MiniAI Sentinel protections",
    "Improved website compatibility and stability",
  ],

  artifacts: shadowGenerated.artifacts.map(
    ({ sha256: _sha256, ...artifact }) =>
      artifact
  ),
};

const cocoaRelease: Release = {
  ...cocoaGenerated,

  highlights: [
    "Improved privacy and fingerprinting protections",
    "Improved website and verification compatibility",
    "Refined WebKit content filtering and tracker resistance",
    "Improved native macOS accent and interface behavior",
  ],

  artifacts: cocoaGenerated.artifacts.map(
    ({ sha256: _sha256, ...artifact }) =>
      artifact
  ),
};

export const releases: Release[] = [
  shadowRelease,
  cocoaRelease,
];
